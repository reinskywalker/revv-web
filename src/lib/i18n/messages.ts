export type WebMessageKey = keyof (typeof WEB_MESSAGES)["en"];

export function normalizeWebLocale(raw?: string | null): WebLocale {
  const clean = (raw ?? "").trim().toLowerCase().slice(0, 2);
  if (clean === "id" || clean === "ja" || clean === "de") return clean;
  return "en";
}

export function formatWebMessage(
  locale: WebLocale,
  key: WebMessageKey,
  params?: Record<string, string | number>,
): string {
  const dict = WEB_MESSAGES[locale] ?? WEB_MESSAGES.en;
  let template: string = dict[key] ?? WEB_MESSAGES.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}
